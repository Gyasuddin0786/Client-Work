/**
 * Projects displayed on the homepage.
 */
export const featuredProjects = projects.filter(
  (project) => project.featured
);

/**
 * Find one project using its public URL slug.
 *
 * Example:
 * getProjectBySlug("modern-main-gate")
 */
export function getProjectBySlug(slug) {
  return projects.find((project) => project.slug === slug);
}

/**
 * Unique portfolio categories.
 *
 * Useful for Portfolio page filters.
 */
export const projectCategories = [
  ...new Set(projects.map((project) => project.category)),
];

/**
 * Find projects connected to a particular service.
 *
 * Useful on ServiceDetails page:
 * "Related Projects"
 */
export function getProjectsByService(serviceSlug) {
  return projects.filter(
    (project) => project.serviceSlug === serviceSlug
  );
}