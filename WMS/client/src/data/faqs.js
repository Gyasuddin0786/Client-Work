/**
 * FAQs suitable for the homepage.
 */
export const featuredFaqs = faqs.filter(
  (faq) => faq.featured
);

/**
 * Get FAQs belonging to a particular category.
 *
 * Example:
 * getFaqsByCategory("quotation")
 */
export function getFaqsByCategory(category) {
  return faqs.filter(
    (faq) => faq.category === category
  );
}

/**
 * Get FAQs specifically connected to a service.
 *
 * Example:
 * getFaqsByService("gate-fabrication")
 */
export function getFaqsByService(serviceSlug) {
  return faqs.filter(
    (faq) => faq.serviceSlug === serviceSlug
  );
}

/**
 * Get general FAQs plus FAQs for a particular service.
 *
 * Useful on ServiceDetails pages.
 */
export function getServicePageFaqs(serviceSlug) {
  return faqs.filter(
    (faq) =>
      faq.serviceSlug === serviceSlug ||
      faq.category === "general"
  );
}